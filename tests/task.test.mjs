// 任务状态机的测试。
//
// 这里测的不是"功能能不能跑"，而是**能不能挡住错的事**：
// 用户随口一句"行"会不会把钱花掉？模型报个超预算的价会不会照样下单？
// 用户说"算了"的时候任务会不会真的停？
//
// 跑：node tests/task.test.mjs

import assert from 'node:assert/strict'
import { 新任务, 推进任务, 判意图, 任务提示, 任务摘要, 是活的, 该汇报吗, 阶段说法 } from '../lib/task.js'

let 过 = 0
const 测 = (名, fn) => {
  try {
    fn()
    过 += 1
    console.log(`  ✓ ${名}`)
  } catch (error) {
    console.error(`  ✗ ${名}\n    ${(error && error.message) || error}`)
    process.exitCode = 1
  }
}

const 现在 = 1_800_000_000_000
const 造 = (预算 = 100) => 新任务({ 现在, 念头: '想买个玩偶', 预算上限: 预算 })

console.log('task（任务状态机）')

// ── 意图识别：这是整个流程的安全底座 ──

测('「可以」只算批准，不算确认花钱', () => {
  for (const 词 of ['可以', '行', '好', '好的', '嗯', '去吧', '看看', '你看着办', 'ok', 'OK']) {
    assert.equal(判意图(词), '批准', `「${词}」应该只是批准`)
  }
})

测('「买吧」「下单」才算确认花钱', () => {
  for (const 词 of ['买吧', '买了', '就它', '下单', '付款', '拍下', '确认', '就要这个', '买']) {
    assert.equal(判意图(词), '确认', `「${词}」应该是确认`)
  }
})

测('取消优先于一切（「别买了」不能被听成「买」）', () => {
  for (const 词 of ['算了', '别买了', '不买了', '不要了', '取消', '停下', '先别', '不用了', '回来吧']) {
    assert.equal(判意图(词), '取消', `「${词}」应该取消`)
  }
  // 含「买」字但意思是别买 —— 这个必须挡住
  assert.equal(判意图('别买了'), '取消')
  assert.notEqual(判意图('别买了'), '确认')
})

测('拒绝和确认分得开', () => {
  assert.equal(判意图('不行'), '拒绝')
  assert.equal(判意图('太贵了'), '拒绝')
  assert.equal(判意图('不'), '拒绝')
  assert.equal(判意图('买吧'), '确认')
})

测('聊天内容不会被当成指令', () => {
  assert.equal(判意图('今天天气真好啊我们去公园散步吧顺便吃点东西'), null)
  assert.equal(判意图(''), null)
  assert.equal(判意图('我在想这个事情到底应该怎么办才好呢'), null)
})

// ── 状态机：不能跳步 ──

测('新任务从「念头」开始，是活的', () => {
  const t = 造()
  assert.equal(t.阶段, '念头')
  assert.ok(是活的(t))
  assert.ok(t.id)
  assert.equal(t.历史.length, 1)
})

测('念头 → 等授权（它得先问）', () => {
  let t = 造()
  t = 推进任务(t, { 类型: '用户说话', 说: '可以', 现在 }).任务
  // 在「念头」阶段用户说"可以"不该跳步 —— 它还没问呢
  assert.equal(t.阶段, '念头', '还没问就批准，不该动')
})

测('等授权 + 「可以」→ 找商品（只授权去看，不授权买）', () => {
  let t = { ...造(), 阶段: '等授权' }
  const r = 推进任务(t, { 类型: '用户说话', 说: '可以', 现在 })
  assert.equal(r.任务.阶段, '找商品')
  assert.equal(r.说话, '好，我去看看。')
})

测('等授权 + 「买吧」也只能进到找商品，不能直接下单', () => {
  const t = { ...造(), 阶段: '等授权' }
  const r = 推进任务(t, { 类型: '用户说话', 说: '买吧', 现在 })
  assert.equal(r.任务.阶段, '找商品', '「买吧」也不能跳过挑商品这一步')
  assert.notEqual(r.任务.阶段, '下单中')
})

测('找商品 + 「可以」什么都不做（别乱跳）', () => {
  const t = { ...造(), 阶段: '找商品' }
  const r = 推进任务(t, { 类型: '用户说话', 说: '可以', 现在 })
  assert.equal(r.任务.阶段, '找商品')
  assert.equal(r.说话, '')
})

测('完整流程：念头→等授权→找商品→等确认→下单中→完成', () => {
  let t = { ...造(200), 阶段: '等授权' }
  t = 推进任务(t, { 类型: '用户说话', 说: '可以', 现在 }).任务
  assert.equal(t.阶段, '找商品')

  const 报 = 推进任务(t, { 类型: '找到商品', 商品: { 名称: '大肥鱼抱枕 45cm', 价格: 39 }, 现在 })
  t = 报.任务
  assert.equal(t.阶段, '等确认')
  assert.equal(t.商品.名称, '大肥鱼抱枕 45cm')
  assert.equal(t.商品.价格, 39)
  assert.ok(报.要问, '这时候该等用户回话')

  t = 推进任务(t, { 类型: '用户说话', 说: '买吧', 现在 }).任务
  assert.equal(t.阶段, '下单中')

  t = 推进任务(t, { 类型: '下单成功', 现在 }).任务
  assert.equal(t.阶段, '完成')
  assert.equal(t.已花, 39)
  assert.ok(!是活的(t), '完成的任务不再是活的')
})

// ── 钱的闸 ──

测('超预算的商品不拿来问用户（直接拦掉）', () => {
  const t = { ...造(50), 阶段: '找商品' }
  const r = 推进任务(t, { 类型: '找到商品', 商品: { 名称: '贵耳机', 价格: 429 }, 现在 })
  assert.equal(r.任务.阶段, '找商品', '不该进到等确认')
  assert.equal(r.任务.商品, null, '不该记下这个商品')
  assert.ok(r.警告.includes('超预算'))
  assert.equal(r.说话, '', '不该去问用户一个买不起的东西')
})

测('确认时再核一次价（防模型报错价）', () => {
  // 任务里记的是 39，但商品被改成 429（比如模型报错了），确认时必须拦住
  const t = { ...造(50), 阶段: '等确认', 商品: { 名称: 'x', 价格: 429 } }
  const r = 推进任务(t, { 类型: '用户说话', 说: '买吧', 现在 })
  assert.equal(r.任务.阶段, '失败')
  assert.ok(r.说话.includes('超过'))
  assert.equal(r.警告, '超预算')
})

测('没设预算上限就不拦（0 = 不限）', () => {
  const t = { ...造(0), 阶段: '找商品' }
  const r = 推进任务(t, { 类型: '找到商品', 商品: { 名称: '贵东西', 价格: 9999 }, 现在 })
  assert.equal(r.任务.阶段, '等确认')
})

// ── 叫停 ──

测('任何阶段说「算了」都能停下', () => {
  for (const 阶段 of ['等授权', '找商品', '等确认']) {
    const t = { ...造(), 阶段 }
    const r = 推进任务(t, { 类型: '用户说话', 说: '算了别买了', 现在 })
    assert.equal(r.任务.阶段, '取消', `${阶段} 应该能取消`)
    assert.ok(r.说话, '应该说一句确认停了')
  }
})

测('取消后再说「可以」也不会复活', () => {
  let t = { ...造(), 阶段: '等确认' }
  t = 推进任务(t, { 类型: '用户说话', 说: '算了', 现在 }).任务
  assert.equal(t.阶段, '取消')
  const r = 推进任务(t, { 类型: '用户说话', 说: '可以', 现在 })
  assert.equal(r.任务.阶段, '取消', '取消就是取消，不能被一句话复活')
})

测('超时作废（不会让半小时前的念头突然下单）', () => {
  const t = { ...造(), 阶段: '等确认', 超时: 现在 - 1 }
  const r = 推进任务(t, { 类型: '用户说话', 说: '买吧', 现在 })
  assert.equal(r.任务.阶段, '失败')
  assert.equal(r.警告, '任务超时作废')
})

// ── 失败路径 ──

测('模型说办不成 → 失败，并记下原因', () => {
  const t = { ...造(), 阶段: '找商品' }
  const r = 推进任务(t, { 类型: '失败', 说: '搜索框点不动', 现在 })
  assert.equal(r.任务.阶段, '失败')
  assert.ok(r.任务.历史.some((h) => h.说.includes('搜索框点不动')))
})

测('阶段不对的汇报会被忽略（防止乱跳）', () => {
  const t = { ...造(), 阶段: '等授权' }
  assert.equal(推进任务(t, { 类型: '下单成功', 现在 }).任务.阶段, '等授权')
  assert.equal(推进任务(t, { 类型: '找到商品', 商品: { 名称: 'x', 价格: 1 }, 现在 }).任务.阶段, '等授权')
})

// ── 提示词 ──

测('找商品阶段的提示词明确写了「只许看不许买」', () => {
  const 文 = 任务提示({ ...造(100), 阶段: '找商品' }, { 称呼: '主人' })
  assert.ok(文.includes('只许看不许买'), '必须明确禁止下单')
  assert.ok(文.includes('100'), '要把预算上限说出来')
  assert.ok(文.includes('agency_task'), '要告诉它用哪个工具报告')
  assert.ok(文.includes('phone_ui'), '要给出操作路径')
})

测('下单阶段的提示词说了支付密码要停下', () => {
  const 文 = 任务提示({ ...造(100), 阶段: '下单中', 商品: { 名称: '玩偶', 价格: 39 } }, {})
  assert.ok(/密码|验证码/.test(文))
  assert.ok(文.includes('玩偶'))
})

测('每个活着的阶段都有提示词（不然模型不知道干什么）', () => {
  for (const 阶段 of ['等授权', '找商品', '等确认', '下单中']) {
    const 文 = 任务提示({ ...造(), 阶段 }, { 称呼: '主人' })
    assert.ok(文.length > 30, `${阶段} 的提示词太短`)
  }
})

测('提示词开头点明「不是别人发的消息」（跟内心独白同一个约定）', () => {
  const 文 = 任务提示({ ...造(), 阶段: '等授权' }, {})
  assert.ok(文.includes('不是别人发的消息'))
})

// ── 摘要与汇报 ──

测('摘要说人话', () => {
  const t = { ...造(), 阶段: '等确认', 商品: { 名称: '玩偶', 价格: 39 } }
  const s = 任务摘要(t)
  assert.ok(s.includes('等你确认'))
  assert.ok(s.includes('玩偶'))
  assert.equal(任务摘要(null), '手上没活儿')
})

测('进度汇报有节流（不能每步都刷屏）', () => {
  const t = { ...造(), 阶段: '找商品' }
  assert.equal(该汇报吗(t, 现在 - 1000, 现在), false, '刚说过就不说')
  assert.equal(该汇报吗(t, 现在 - 120000, 现在), true, '隔了 2 分钟可以说')
  assert.equal(该汇报吗({ ...t, 阶段: '等确认' }, 现在 - 120000, 现在), false, '等确认时该说正事，不汇报进度')
})

测('每个阶段都有中文说法', () => {
  for (const 阶段 of ['念头', '等授权', '找商品', '等确认', '下单中', '完成', '取消', '失败']) {
    assert.ok(阶段说法[阶段], `${阶段} 缺说法`)
  }
})

console.log(`\n${过} 项通过${process.exitCode ? '，有失败' : ''}`)
