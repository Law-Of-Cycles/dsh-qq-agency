let 过 = 0
const 测 = (名, fn) => {
  try {
    fn()
    过 += 1
    console.log(`  ✓ ${名}`)
  } catch (error) {
    console.error(`  ✗ ${名}\n    ${error && error.message}`)
    process.exitCode = 1
  }
}

const 现在 = Date.now()
const 固定随机 = (值 = 0.5) => () => 值

