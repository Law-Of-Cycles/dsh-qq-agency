测('构造独白：交代清楚「这不是别人发的消息」，并带上状态与动作要求', () => {
  const 心 = 默认内心(现在)
  心.无聊 = 0.8
  心.想念 = 0.6
  心.主人最后说话 = 现在 - 3 * 3600 * 1000
  const 决定 = { 动作: 'speak_group', 分数: 0.7, 理由: '群里安静太久，我有点无聊', 群号: '123', 冲动们: {} }
  const 文 = 构造独白(心, 决定, {
    现在,
    群们: [{ 群号: 123, 名称: '测试群', 新消息: 3, 最后一条: '今天吃啥', 提到我: false }],
    主人: {},
    手机: { 在线: true, 电量: 66, 前台: 'com.tencent.mobileqq' },
  }, { 称呼: '主人' })

  assert.ok(文.includes('不是别人发给你的消息'), '必须交代清楚独白的身份')
  assert.ok(文.includes('测试群'), '要带上群名')
  assert.ok(文.includes('今天吃啥'), '要带上群里最后说的话')
  assert.ok(文.includes('66'), '要带上手机电量')
  assert.ok(文.includes('群里安静太久'), '要带上它自己的理由')
  assert.ok(文.includes('直接给出发出去的话'), '要说明输出格式')
  assert.ok(!文.includes('undefined'), '不能漏出 undefined')
})

