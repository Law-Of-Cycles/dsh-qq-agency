// 任务：一件要做几分钟、中间要跟人说话、还能被人叫停的事。
//
// 为什么单独一层：原来的心跳是「冲动 → 说一句 → 完事」，一句话就结束了。
// 但「去拼多多买个玩偶」不是一句话：要问许可、要挑、要再确认、要下单，
// 中间隔着好几分钟，用户随时可能改主意。这需要**状态**，而且状态要落盘。
//
// 这个文件是纯的：不读文件、不发网络、不看时间。所有副作用在 host.js 里。
// 好处是「给多少钱算超支」「用户说算了算不算取消」这些判断都能直接单测。

/** 阶段按顺序推进，后面的不会退回前面的（取消/失败是出口）。 */
export const 阶段们 = ['念头', '等授权', '找商品', '等确认', '下单中', '完成', '取消', '失败']

const 出口 = new Set(['完成', '取消', '失败'])

export const 是活的 = (任务) => !!任务 && !出口.has(任务.阶段)

/** 阶段 → 人话（给日志和 QQ 消息用）。 */
export const 阶段说法 = {
  念头: '刚想到',
  等授权: '在等你点头',
  找商品: '在挑东西',
  等确认: '在等你确认',
  下单中: '在下单',
  完成: '办完了',
  取消: '你叫停了',
  失败: '没办成',
}

/**
 * 从用户说的话里判断意图。
 *
 * 这是整个流程里最容易做错的一环：**「可以」和「买吧」不是一回事**。
 * 「可以」是允许你去看看，「买」才是允许花钱。混在一起就会出现
 * 用户随口一句"行"就把钱花掉的情况。所以分两档返回。
 *
 * @returns {'批准'|'确认'|'拒绝'|'取消'|'催促'|null}
 */
export function 判意图(文字) {
  const 文 = String(文字 || '').trim()
  if (!文 || 文.length > 40) return null // 太长的大概率是聊天，不是指令

  // 取消优先：「别买了」「算了」比「买」更该被听见
  if (/算了|不买了|别买了|不要了|取消|停(?:下|止)|先别|不用了|不弄了|回来吧/.test(文)) return '取消'

  // 拒绝：明确说不
  if (/^(?:不|别|否|no|nope)[。！!.\s]*$/i.test(文) || /不行|不可以|不好|不用|不想|别买|太贵|买不起/.test(文)) return '拒绝'

  // 确认：明确说要花钱。必须比「批准」更强 —— 这里出现误判就是真的花钱
  if (/买吧|买了|就它|就要这个|下单|付款|拍下|这个可以|确认|确定买|buy/i.test(文)) return '确认'
  if (/^(?:买|要|来|整|搞)(?:吧|了|一个|这个)?[。！!.\s]*$/.test(文)) return '确认'

  // 批准：允许你去做，但还没到掏钱
  // 允许带语气词（好的呀 / 可以啊 / 嗯嗯）—— 真人说话就是这样，太严会漏
  if (/^(?:可以|行|好|嗯|成|中|准|对|yes|ok)[呀啊嘛呗的了哦欸]*[。！!.\s]*$/i.test(文)) return '批准'
  if (/可以啊|行啊|去吧|看看|你看着办|随便你|你决定|挑一个|你选/.test(文)) return '批准'

  // 催促
  if (/怎么样了|好了没|买到没|还没|快点|搞定了吗|进展/.test(文)) return '催促'

  return null
}

/**
 * 造一个新任务。
 *
 * @param {object} 参数 { 现在, 念头, 类型, 预算上限 }
 */
export function 新任务({ 现在 = Date.now(), 念头 = '', 类型 = '购物', 预算上限 = 0 } = {}) {
  return {
    id: `t${现在.toString(36)}${Math.floor(Math.random() * 1296).toString(36).padStart(2, '0')}`,
    类型,
    念头: String(念头 || '').slice(0, 200),
    阶段: '念头',
    预算上限: Math.max(0, Number(预算上限) || 0),
    商品: null, // { 名称, 价格, 位置 }
    已花: 0,
    建时: 现在,
    改时: 现在,
    超时: 现在 + 45 * 60 * 1000, // 45 分钟没推进就作废，免得半夜还挂着
    历史: [{ 时: 现在, 阶段: '念头', 说: '起了个念头' }],
  }
}

/** 记一步（内部用）。 */
function 走一步(任务, 阶段, 说, 现在) {
  const 新 = {
    ...任务,
    阶段,
    改时: 现在,
    历史: [...(任务.历史 || []), { 时: 现在, 阶段, 说: String(说 || '').slice(0, 200) }].slice(-30),
  }
  return 新
}

/**
 * 推进任务。
 *
 * @param {object} 任务   当前任务（可为 null）
 * @param {object} 事件   { 类型, 现在, 商品, 说 }
 * @returns {{任务: object|null, 说话: string, 要问: boolean, 警告: string}}
 *   说话 = 该发给用户的话（空字符串表示这步不用开口）
 *   要问 = 是否在等用户回话（等的话，心跳不该再自作主张）
 */
export function 推进任务(任务, 事件 = {}, 配置 = {}) {
  const 现在 = Number(事件.现在) || Date.now()
  const 空 = { 任务: 任务 || null, 说话: '', 要问: false, 警告: '' }
  if (!任务) return 空

  // 超时：挂了太久就作废，别让一个半小时前的念头突然下单
  if (是活的(任务) && 现在 > (任务.超时 || 0)) {
    return {
      任务: 走一步(任务, '失败', '挂太久，作废了', 现在),
      说话: '',
      要问: false,
      警告: '任务超时作废',
    }
  }

  if (出口.has(任务.阶段)) return 空

  const 类型 = String(事件.类型 || '')
  const 上限 = Number(任务.预算上限) || 0

  // ── 用户回话 ──
  if (类型 === '用户说话') {
    const 意图 = 判意图(事件.说)
    if (!意图) return 空

    if (意图 === '取消') {
      return {
        任务: 走一步(任务, '取消', `用户说「${String(事件.说).slice(0, 40)}」`, 现在),
        说话: '好，不弄了。',
        要问: false,
        警告: '',
      }
    }

    if (意图 === '拒绝') {
      return {
        任务: 走一步(任务, '取消', `用户拒绝了：「${String(事件.说).slice(0, 40)}」`, 现在),
        说话: '行，那我不买了。',
        要问: false,
        警告: '',
      }
    }

    if (意图 === '催促') {
      return { 任务, 说话: '', 要问: 任务.阶段 === '等授权' || 任务.阶段 === '等确认', 警告: '' }
    }

    if (意图 === '批准' && 任务.阶段 === '等授权') {
      return { 任务: 走一步(任务, '找商品', '用户点头了，可以去看', 现在), 说话: '好，我去看看。', 要问: false, 警告: '' }
    }

    if (意图 === '确认' && 任务.阶段 === '等确认') {
      // 关键闸：确认的时候再核一次价格，防止模型报的价和实际不符
      const 价 = Number(任务.商品 && 任务.商品.价格) || 0
      if (上限 > 0 && 价 > 上限) {
        return {
          任务: 走一步(任务, '失败', `价格 ${价} 超过上限 ${上限}，不下单`, 现在),
          说话: `这个要 ${价} 块，超过你给的 ${上限} 了，我没下单。`,
          要问: false,
          警告: '超预算',
        }
      }
      return { 任务: 走一步(任务, '下单中', '用户确认了，可以下单', 现在), 说话: '好，下单了。', 要问: false, 警告: '' }
    }

    // 「买吧」出现在还没确认商品的时候：理解成"你看着办"，但**不能跳步**
    if (意图 === '确认' && 任务.阶段 === '等授权') {
      return { 任务: 走一步(任务, '找商品', '用户说买吧，可以去看', 现在), 说话: '好，我去挑一个。', 要问: false, 警告: '' }
    }

    // 其它组合（比如在"找商品"时用户说"可以"）什么都不做，别乱跳
    return 空
  }

  // ── 模型报告：找到商品了 ──
  if (类型 === '找到商品') {
    if (任务.阶段 !== '找商品') return 空
    const 名 = String((事件.商品 && 事件.商品.名称) || '').trim()
    const 价 = Number(事件.商品 && 事件.商品.价格) || 0
    if (!名) return { ...空, 警告: '没给商品名' }

    // 超预算的商品不该拿来问 —— 直接拦掉，别让用户看见一个买不起的东西
    if (上限 > 0 && 价 > 上限) {
      return {
        任务: 走一步(任务, '找商品', `看到「${名}」${价} 块，超预算 ${上限}，换一个`, 现在),
        说话: '',
        要问: false,
        警告: `超预算（${价} > ${上限}），换一个`,
      }
    }

    const 新 = 走一步({ ...任务, 商品: { 名称: 名.slice(0, 120), 价格: 价, 位置: String((事件.商品 && 事件.商品.位置) || '').slice(0, 120) } }, '等确认', `挑中「${名}」${价} 块`, 现在)
    return { 任务: 新, 说话: '', 要问: true, 警告: '' }
  }

  // ── 模型报告：下好单了 ──
  if (类型 === '下单成功') {
    if (任务.阶段 !== '下单中') return 空
    const 价 = Number(任务.商品 && 任务.商品.价格) || 0
    return {
      任务: 走一步({ ...任务, 已花: 价 }, '完成', `下单成功，花了 ${价}`, 现在),
      说话: '',
      要问: false,
      警告: '',
    }
  }

  // ── 模型报告：办不成 ──
  if (类型 === '失败') {
    return {
      任务: 走一步(任务, '失败', String(事件.说 || '没办成').slice(0, 150), 现在),
      说话: '',
      要问: false,
      警告: '',
    }
  }

  return 空
}

/**
 * 给模型的提示词：这一步该干什么、能说什么。
 *
 * 分开写而不是让模型自己猜，是因为**它不知道现在能不能花钱**。
 * 提示词里明确"你现在只能看不能买"，它才不会自作主张下单。
 */
export function 任务提示(任务, 配置 = {}) {
  if (!任务) return ''
  const 称呼 = 配置.称呼 || '主人'
  const 上限 = Number(任务.预算上限) || 0
  const 钱 = 上限 > 0 ? `预算上限 ${上限} 块（超过这个数不许买）` : '没设预算上限（自己看着办，别挑贵的）'
  const 头 = '（这是你自己心里的事，不是别人发的消息。）'

  if (任务.阶段 === '等授权') {
    return [
      头,
      `你刚想到一件事：${任务.念头}`,
      `你想去做，但得先问${称呼}同不同意。${钱}。`,
      `用你平时说话的样子问他一句 —— 说清你想干什么、大概多少钱。别解释，直接给出发出去的话。`,
    ].join('\n')
  }

  if (任务.阶段 === '找商品') {
    return [
      头,
      `${称呼}同意了（${任务.念头}）。现在手机在你手上。`,
      `${钱}。`,
      '',
      '去做：',
      '1. 用 phone_ui 看屏幕上有什么（读不到就隔 1-2 秒重试，或 phone_look 截图）',
      '2. 用 phone_tap_text 按文字点（比猜坐标准）',
      '3. 搜到东西、看到价格后，用 agency_task 报告：动作=找到商品，商品名、价格',
      '',
      '⚠ 只许看不许买：不许点「立即购买」「发起拼单」「提交订单」。挑好了要等对方再点头。',
      '如果实在找不到合适的，用 agency_task 报告 动作=失败，说清卡在哪。',
    ].join('\n')
  }

  if (任务.阶段 === '等确认') {
    const 商 = 任务.商品 || {}
    return [
      头,
      `你挑中了：${商.名称}${商.价格 ? `，${商.价格} 块` : ''}。`,
      `现在得回去问${称呼}买不买这一个。`,
      '把商品名和价格说清楚，问一句买不买。别解释，直接给出发出去的话。',
    ].join('\n')
  }

  if (任务.阶段 === '下单中') {
    const 商 = 任务.商品 || {}
    return [
      头,
      `${称呼}确认了，可以下单：${商.名称}${商.价格 ? `，${商.价格} 块` : ''}。`,
      '',
      '去点下单（phone_tap_text 点「立即购买」「发起拼单」「提交订单」这类按钮）。',
      '办成了用 agency_task 报告 动作=下单成功。',
      '',
      '⚠ 到支付密码 / 验证码就停下 —— 你不知道密码，也不该知道。',
      '那一步用 agency_task 报告 动作=失败，说"要你输密码"。',
    ].join('\n')
  }

  return ''
}

/** 一行摘要（给设置页和日志）。 */
export function 任务摘要(任务) {
  if (!任务) return '手上没活儿'
  const 阶段 = 阶段说法[任务.阶段] || 任务.阶段
  const 商 = 任务.商品 ? `「${任务.商品.名称}」${任务.商品.价格 ? ` ${任务.商品.价格}块` : ''}` : ''
  return `${阶段}${商 ? ` · ${商}` : ''} · ${任务.念头 || ''}`.slice(0, 120)
}

/**
 * 挑一个「值得主动说」的时机。
 *
 * 进度汇报不能每步都发 —— 那会变成刷屏。只在阶段变了、或隔了够久才说一句。
 */
export function 该汇报吗(任务, 上次汇报时, 现在 = Date.now(), 最短间隔毫秒 = 90000) {
  if (!任务) return false
  const 上次 = Number(上次汇报时) || 0
  if (现在 - 上次 < 最短间隔毫秒) return false
  return ['找商品', '下单中'].includes(任务.阶段)
}
