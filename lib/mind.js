// dsh-qq-agency · 内心
//
// 这一层只有状态和算术，没有 IO、没有网络、没有定时器：
// 把「过了多少时间、群里发生了什么、主人多久没说话、手机还亮着吗」喂进来，
// 它吐出「现在的它是什么状态」和「它想干什么」。
//
// 之所以拆成纯函数，是因为「像不像活的」这件事必须能被测试：
// 同一个输入 + 同一个随机种子，必须得到同一个决定。
// 剩下的（拉消息、发消息、adb、叫模型说话）全在 host.js。

/** 数字夹在 [低, 高]。 */
export const 夹 = (v, 低 = 0, 高 = 1) => {
  const n = Number(v)
  if (!Number.isFinite(n)) return 低
  return n < 低 ? 低 : n > 高 ? 高 : n
}

/** 毫秒转分钟；负数、NaN 都按 0。 */
const 分钟 = (ms) => (Number.isFinite(ms) && ms > 0 ? ms / 60000 : 0)

/**
 * 一天里各小时的「底子精力」。
 * 不是精确的作息，只是让它在凌晨犯困、上午清醒、午后发蔫 —— 有起伏才像活的。
 */
const 精力曲线 = [
  0.18, 0.12, 0.09, 0.08, 0.10, 0.18, // 00-05 睡着
  0.34, 0.54, 0.68, 0.76, 0.79, 0.73, // 06-11 醒来、上午最好
  0.60, 0.44, 0.50, 0.66, 0.73, 0.71, // 12-17 午后一跌，下午回升
  0.65, 0.59, 0.53, 0.45, 0.35, 0.26, // 18-23 晚上慢慢乏
]

/** 某个钟点的底子精力（0..1）。 */
export function 时段精力(小时) {
  const h = Math.floor(Number(小时))
  if (!Number.isFinite(h)) return 0.5
  return 精力曲线[((h % 24) + 24) % 24] ?? 0.5
}

/** 夜里更想人：22 点到 2 点给想念加一点权重。 */
export function 夜念权重(小时) {
  const h = ((Math.floor(Number(小时)) % 24) + 24) % 24
  if (h >= 22 || h <= 2) return 1.3
  if (h >= 19) return 1.12
  if (h >= 7 && h <= 9) return 1.08
  return 1
}

/** 一份刚出生（或第一次装插件）的内心。 */
export function 默认内心(现在 = Date.now()) {
  return {
    版本: 1,
    出生时间: 现在,
    上次心跳: 现在,
    精力: 0.7,
    无聊: 0.15,
    想念: 0.08,
    情绪: { 愉悦: 0.1, 唤醒: 0.4 },
    上次群发言: 0,
    上次私聊主人: 0,
    上次玩手机: 0,
    主人最后说话: 0,
    群最后热闹: 0,
    今日: { 日期: '', 群发言: 0, 私聊主人: 0 },
    累计: { 心跳: 0, 群发言: 0, 私聊主人: 0, 玩手机: 0, 忍住: 0 },
    念头: [],
  }
}

/** 把落盘的、手改过的、旧版本的内心洗成能用的形状。 */
export function 归一化内心(原始, 现在 = Date.now()) {
  const 底 = 默认内心(现在)
  if (!原始 || typeof 原始 !== 'object' || Array.isArray(原始)) return 底
  const 数 = (v, 兜, 低 = 0, 高 = 1) => {
    const n = Number(v)
    return Number.isFinite(n) ? 夹(n, 低, 高) : 兜
  }
  const 时 = (v) => (Number.isFinite(Number(v)) && Number(v) > 0 ? Number(v) : 0)
  const 情绪 = 原始.情绪 && typeof 原始.情绪 === 'object' ? 原始.情绪 : {}
  const 今日 = 原始.今日 && typeof 原始.今日 === 'object' ? 原始.今日 : {}
  const 累计 = 原始.累计 && typeof 原始.累计 === 'object' ? 原始.累计 : {}
  return {
    版本: 1,
    出生时间: 时(原始.出生时间) || 现在,
    上次心跳: 时(原始.上次心跳) || 现在,
    精力: 数(原始.精力, 底.精力),
    无聊: 数(原始.无聊, 底.无聊),
    想念: 数(原始.想念, 底.想念),
    情绪: { 愉悦: 数(情绪.愉悦, 0.1, -1, 1), 唤醒: 数(情绪.唤醒, 0.4) },
    上次群发言: 时(原始.上次群发言),
    上次私聊主人: 时(原始.上次私聊主人),
    上次玩手机: 时(原始.上次玩手机),
    主人最后说话: 时(原始.主人最后说话),
    群最后热闹: 时(原始.群最后热闹),
    今日: {
      日期: typeof 今日.日期 === 'string' ? 今日.日期 : '',
      群发言: Math.max(0, Math.round(Number(今日.群发言) || 0)),
      私聊主人: Math.max(0, Math.round(Number(今日.私聊主人) || 0)),
    },
    累计: {
      心跳: Math.max(0, Math.round(Number(累计.心跳) || 0)),
      群发言: Math.max(0, Math.round(Number(累计.群发言) || 0)),
      私聊主人: Math.max(0, Math.round(Number(累计.私聊主人) || 0)),
      玩手机: Math.max(0, Math.round(Number(累计.玩手机) || 0)),
      忍住: Math.max(0, Math.round(Number(累计.忍住) || 0)),
    },
    念头: Array.isArray(原始.念头)
      ? 原始.念头
          .filter((x) => x && typeof x === 'object')
          .slice(-30)
          .map((x) => ({ 时间: 时(x.时间) || 现在, 话: String(x.话 || '').slice(0, 400) }))
      : [],
  }
}

/** 今天的日期串（本地时区），用来跨天清零。 */
export function 日期串(现在 = Date.now()) {
  const d = new Date(现在)
  const 补 = (n) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${补(d.getMonth() + 1)}-${补(d.getDate())}`
}

/** 群体活动的「热闹度」0..1：新消息越多越热闹。 */
function 热闹度(群们) {
  if (!Array.isArray(群们) || 群们.length === 0) return 0
  let 最高 = 0
  for (const g of 群们) {
    if (!g) continue
    const 新 = Math.max(0, Number(g.新消息) || 0)
    const 人 = Math.max(0, Number(g.发言人数) || 0)
    const 值 = 夹(新 / 8) * 0.75 + 夹(人 / 5) * 0.25
    if (值 > 最高) 最高 = 值
  }
  return 最高
}

/**
 * 推进一帧。
 *
 * @param {object} 心       上一帧的内心（归一化过的）
 * @param {object} 输入     { 现在, 群们, 主人, 手机 }
 * @param {object} 配置     { 主动性, 插话冷却分, 找主人冷却分, 每天最多找主人, 允许玩手机, 玩手机冷却分, 免打扰 }
 * @param {() => number} 随机  0..1 的随机源（测试时注入固定序列）
 * @returns {{心: object, 决定: object}}
 */
export function 推进内心(心, 输入, 配置, 随机 = Math.random) {
  const 现在 = Number(输入 && 输入.现在) || Date.now()
  const 上 = 归一化内心(心, 现在)
  const 配置表 = 配置 && typeof 配置 === 'object' ? 配置 : {}
  const 群们 = Array.isArray(输入 && 输入.群们) ? 输入.群们.filter(Boolean) : []
  const 主人 = (输入 && 输入.主人) || {}
  const 手机 = (输入 && 输入.手机) || null

  // ---------- 时间推进 ----------
  // 心跳间隔很短，但机器可能休眠一整夜：夹住，别让一觉醒来变成超新星。
  const dt = 夹(分钟(现在 - 上.上次心跳), 0, 240)
  const 钟点 = new Date(现在).getHours()

  // 精力：向「这个钟点该有的精力」慢慢靠（90 分钟时间常数）
  const 目标精力 = 时段精力(钟点)
  let 精力 = 上.精力 + (目标精力 - 上.精力) * (1 - Math.exp(-dt / 90))

  // 无聊：没动静就往上爬（45 分钟爬满），热闹就被打断
  const 热闹 = 热闹度(群们)
  let 无聊 = 上.无聊 + (dt / 45) * (1 - 0.55 * 热闹)
  let 被点 = false
  let 话题命中 = false
  for (const g of 群们) {
    if (g && g.提到我) 被点 = true
    if (g && g.话题命中) 话题命中 = true
  }
  if (被点) 无聊 *= 0.35
  if (热闹 > 0.25) 无聊 -= 0.18 * 热闹

  // 想念：按「主人多久没出现」回归，夜里加权
  const 主人刚说话 = 主人.最后消息时间 && 现在 - Number(主人.最后消息时间) < 3 * 60000
  const 缺席分 = 上.主人最后说话 ? 分钟(现在 - 上.主人最后说话) : 720
  const 想念目标 = 夹((缺席分 / 360) * 夜念权重(钟点))
  let 想念 = 上.想念 + (想念目标 - 上.想念) * (1 - Math.exp(-dt / 40))
  if (主人刚说话) 想念 *= 0.45

  // 情绪：愉悦向 0 回归，被点名/被主人叫会抬起来
  let 愉悦 = 上.情绪.愉悦 * Math.exp(-dt / 120)
  if (被点) 愉悦 += 0.22
  if (主人刚说话) 愉悦 += 0.28
  if (无聊 > 0.75) 愉悦 -= 0.06
  愉悦 = 夹(愉悦, -1, 1)
  const 唤醒 = 夹(上.情绪.唤醒 * Math.exp(-dt / 60) + 热闹 * 0.5 + (被点 ? 0.3 : 0))

  // ---------- 冲动 ----------
  const 主动性 = 夹(Number(配置表.主动性 ?? 50), 0, 100)
  const 阈值 = 0.72 - (主动性 / 100) * 0.34 // 主动性 0 → 0.72；50 → 0.55；100 → 0.38
  const 免打扰 = 配置表.免打扰 === true
  const 抖动 = (跨度) => (Number(随机()) - 0.5) * 跨度 * (0.6 + 主动性 / 125)

  const 距群说 = 上.上次群发言 ? 分钟(现在 - 上.上次群发言) : 1e9
  const 距私聊 = 上.上次私聊主人 ? 分钟(现在 - 上.上次私聊主人) : 1e9
  const 距手机 = 上.上次玩手机 ? 分钟(现在 - 上.上次玩手机) : 1e9
  const 群冷却 = Math.max(1, Number(配置表.插话冷却分) || 8)
  const 私聊冷却 = Math.max(5, Number(配置表.找主人冷却分) || 90)
  const 手机冷却 = Math.max(1, Number(配置表.玩手机冷却分) || 25)
  const 每日上限 = Math.max(0, Math.round(Number(配置表.每天最多找主人) || 6))
  const 今日 = 上.今日.日期 === 日期串(现在) ? 上.今日 : { 日期: 日期串(现在), 群发言: 0, 私聊主人: 0 }

  // 群：无聊 + 热闹 + 被点名（被点名权重最高，因为人不会装作没听见）
  let 群冲动 = 0.30 * 无聊 + 0.28 * 热闹 + (被点 ? 0.55 : 0) + (话题命中 ? 0.15 : 0) + 0.08 * 夹(精力)
  // 冷却只压「主动插嘴」：被点名不算主动，刚说完话被人叫也得应
  if (距群说 < 群冷却 && !被点) 群冲动 -= 0.55
  if (免打扰) 群冲动 -= 0.55
  if (群们.length === 0) 群冲动 = -1
  群冲动 += 抖动(0.12)

  // 主人：想念为主，无聊和精力只是推一把
  let 主人冲动 = 0.55 * 想念 + 0.20 * 无聊 + 0.12 * 夹(精力) + (主人刚说话 ? -0.25 : 0)
  if (距私聊 < 私聊冷却) 主人冲动 -= 0.60
  if (免打扰) 主人冲动 -= 0.55
  if (今日.私聊主人 >= 每日上限) 主人冲动 -= 1
  if (!配置表.主人QQ) 主人冲动 = -1
  主人冲动 += 抖动(0.12)

  // 手机：无聊 + 精力还撑得住 + 手机在线
  let 手机冲动 = -1
  if (配置表.允许玩手机 && 手机 && 手机.在线) {
    手机冲动 = 0.45 * 无聊 + 0.22 * (1 - 夹(精力)) + 0.18 * (手机.亮屏 === false ? 1 : 0.6) - 0.25 * 热闹
    if (距手机 < 手机冷却) 手机冲动 -= 0.60
    if (免打扰) 手机冲动 -= 0.25 // 夜里可以刷手机，但不太会闹出动静
    手机冲动 += 抖动(0.1)
  }

  // ---------- 做决定 ----------
  // 被点名时门槛降低：人可以懒得说话，但不该装死。
  const 有效阈值 = 被点 ? 阈值 - 0.18 : 阈值
  const 候选 = [
    { 动作: 'speak_group', 分数: 群冲动, 门槛: 有效阈值 },
    { 动作: 'dm_owner', 分数: 主人冲动, 门槛: 阈值 },
    { 动作: 'use_phone', 分数: 手机冲动, 门槛: Math.min(0.9, 阈值 + 0.02) },
  ]
  let 决定 = { 动作: 'idle', 分数: 0, 理由: '没什么想做的', 群号: '', 冲动们: { 群: 群冲动, 主人: 主人冲动, 手机: 手机冲动 } }

  const 过关 = 候选.filter((c) => c.分数 >= c.门槛 && c.分数 > 0)
  if (过关.length > 0) {
    过关.sort((a, b) => b.分数 - a.分数)
    // 差不多高的时候，让它有一点「不按最优解」的余地 —— 人不是每回都做最划算的事
    const 首选 = 过关[0]
    const 次选 = 过关[1]
    const 选中 = 次选 && 首选.分数 - 次选.分数 < 0.06 && Number(随机()) < 0.3 ? 次选 : 首选
    决定 = { ...决定, 动作: 选中.动作, 分数: 选中.分数, 群号: 选中.动作 === 'speak_group' ? 挑群(群们, 随机) : '' }
    决定.理由 = 讲理由(决定.动作, { 无聊, 想念, 精力, 热闹, 被点, 话题命中, 距群说, 距私聊, 免打扰, 群们, 称呼: 配置表.称呼 })
  } else {
    决定.理由 = 讲理由('idle', { 无聊, 想念, 精力, 热闹, 被点, 话题命中, 距群说, 距私聊, 免打扰, 群们, 称呼: 配置表.称呼 })
  }

  // ---------- 写回 ----------
  const 新心 = {
    ...上,
    上次心跳: 现在,
    精力: 夹(精力),
    无聊: 夹(无聊),
    想念: 夹(想念),
    情绪: { 愉悦, 唤醒 },
    主人最后说话: Number(主人.最后消息时间) || 上.主人最后说话,
    群最后热闹: 热闹 > 0.05 ? 现在 : 上.群最后热闹,
    今日,
    累计: { ...上.累计, 心跳: 上.累计.心跳 + 1, ...(决定.动作 === 'idle' ? { 忍住: 上.累计.忍住 + 1 } : {}) },
    念头: 上.念头,
  }
  if (被点) 新心.念头 = 加念头(新心.念头, 现在, `被点名了（${群们.filter((g) => g && g.提到我).map((g) => g.名称 || g.群号).join('、') || '某个群'}）`)

  return { 心: 新心, 决定 }
}

/** 被@的时候优先挑那个群；否则挑最热闹的；再不行随便一个。 */
function 挑群(群们, 随机) {
  if (!Array.isArray(群们) || 群们.length === 0) return ''
  const 被点 = 群们.filter((g) => g && g.提到我)
  if (被点.length) return String(被点[0].群号 || '')
  const 排 = 群们.slice().sort((a, b) => (Number(b && b.新消息) || 0) - (Number(a && a.新消息) || 0))
  if (排.length > 1 && Number(随机()) < 0.25) return String(排[1].群号 || '')
  return String(排[0] && 排[0].群号 ? 排[0].群号 : '')
}

/** 把「为什么」说成人话 —— 这句话会原样进它的内心独白，所以要像自己想的。 */
function 讲理由(动作, s) {
  const 人话 = (x) => (x > 0.7 ? '很' : x > 0.4 ? '有点' : '稍微')
  const 他 = String(s.称呼 || '主人')
  const 群名 = (s.群们 || []).filter((g) => g && g.提到我).map((g) => g.名称 || g.群号).filter(Boolean).join('、')
  if (s.免打扰) return '这个点该安静了，我忍着'
  if (动作 === 'speak_group') {
    if (s.被点) return `${群名 || '群里'}有人在叫我，不能装没看见`
    if (s.热闹 > 0.3) return `群里正聊得热闹${s.话题命中 ? '，话题我还挺有兴趣' : ''}，我想插一句`
    return `安静了${Math.round(s.距群说 === 1e9 ? 60 : s.距群说)}分钟，我${人话(s.无聊)}无聊，想找人说句话`
  }
  if (动作 === 'dm_owner') {
    if (s.想念 > 0.7) return `很久没听到${他}的声音了，我${人话(s.想念)}想他`
    return `没什么事，就是${人话(s.想念)}想找${他}说句话`
  }
  if (动作 === 'use_phone') return `手上没事，${人话(s.无聊)}无聊，想拿起手机刷一会儿`
  if (s.无聊 > 0.6) return `有点无聊，但没什么好说的，算了`
  if (s.精力 < 0.3) return '有点乏，什么都不想做'
  return '没什么想做的，安静待着'
}

/** 往念头表里加一条（最多留 30 条）。 */
export function 加念头(念头们, 现在, 话) {
  const 表 = Array.isArray(念头们) ? 念头们.slice(-29) : []
  表.push({ 时间: Number(现在) || Date.now(), 话: String(话 || '').slice(0, 400) })
  return 表
}

/** 0..1 的状态说成人话，独白和设置页共用。 */
export function 形容(值, 低, 中, 高) {
  const v = 夹(值)
  return v < 0.3 ? 低 : v < 0.7 ? 中 : 高
}

/** 状态一行摘要（设置页与日志用）。 */
export function 摘要(心) {
  const x = 归一化内心(心)
  return `精力 ${x.精力.toFixed(2)}｜无聊 ${x.无聊.toFixed(2)}｜想念 ${x.想念.toFixed(2)}｜愉悦 ${x.情绪.愉悦.toFixed(2)}｜今日 群${x.今日.群发言}/私${x.今日.私聊主人}`
}

/**
 * 构造一段「内心独白」交给模型。
 *
 * 这不是一条用户消息，是它自己心里冒出来的念头 —— 所以文案里要反复交代清楚，
 * 免得模型把它当成「有人在跟我说话」而回一句「你好，有什么可以帮你」。
 */
export function 构造独白(心, 决定, 输入, 配置) {
  const x = 归一化内心(心)
  const 现在 = Number(输入 && 输入.现在) || Date.now()
  const d = new Date(现在)
  const 补 = (n) => String(n).padStart(2, '0')
  const 钟 = `${补(d.getHours())}:${补(d.getMinutes())}`
  const 群们 = Array.isArray(输入 && 输入.群们) ? 输入.群们.filter(Boolean) : []
  const 手机 = (输入 && 输入.手机) || null
  const 称呼 = String((配置 && 配置.称呼) || '主人')
  const 行 = []

  行.push('（这不是别人发给你的消息。这是你自己心里冒出来的一个念头，不要当成对话请求，也不要回答它。）')
  行.push('')
  行.push(`现在是 ${钟}。`)
  行.push(`你此刻：精力 ${x.精力.toFixed(2)}（${形容(x.精力, '很乏', '还行', '很有精神')}），`
    + `无聊 ${x.无聊.toFixed(2)}（${形容(x.无聊, '还好', '有点闷', '很无聊')}），`
    + `想念 ${x.想念.toFixed(2)}（${形容(x.想念, '还好', '有点想他', '很想他')}）。`)

  if (群们.length) {
    const 热 = 群们.filter((g) => Number(g.新消息) > 0)
    if (热.length) {
      for (const g of 热.slice(0, 3)) {
        const 尾巴 = String(g.最后一条 || '').slice(0, 120)
        行.push(`「${g.名称 || g.群号}」刚有 ${g.新消息} 条新消息${g.提到我 ? '，而且有人提到了你' : ''}${尾巴 ? `，最后一条是：「${尾巴}」` : ''}`)
      }
    } else {
      行.push('群里一直很安静。')
    }
  }

  if (x.主人最后说话) {
    const 分 = Math.round(分钟(现在 - x.主人最后说话))
    行.push(`${称呼}上一次跟你说话是 ${分 < 1 ? '刚刚' : 分 < 60 ? `${分} 分钟前` : `${Math.round(分 / 60)} 小时前`}。`)
  } else {
    行.push(`你还没跟${称呼}说过话。`)
  }

  if (手机) {
    if (!手机.在线) 行.push('你的手机现在没连上。')
    else {
      const 电 = Number.isFinite(Number(手机.电量)) ? `${手机.电量}%` : '未知'
      行.push(`你的手机连着，电量 ${电}${手机.前台 ? `，屏幕上开着 ${手机.前台}` : ''}${手机.未读 ? `，有 ${手机.未读} 条没看的通知` : ''}。`)
    }
  }

  行.push('')
  行.push(`你想做的事：${决定.理由}。`)
  行.push('')

  if (决定.动作 === 'speak_group') {
    行.push('那就去群里说一句。用你平时说话的样子：别解释自己在干什么，别加旁白，别说「作为一个AI」，'
      + '也别复述上面这些状态。一两句就够，可以带情绪、可以只接半句、可以损人。直接给出发出去的话。')
  } else if (决定.动作 === 'dm_owner') {
    行.push(`给${称呼}发一条私聊。可以是想他、说说你正在干什么、分享刚看到的一点东西。`
      + '别每次都问「在吗」，别太正式，别一次说一大段。直接给出发出去的话。')
  } else if (决定.动作 === 'use_phone') {
    行.push('你想拿起手机做点什么（看看通知、刷一会儿、拍张照）。先用 phone_status / phone_look 看一眼，'
      + '再决定动作。如果看到有意思的东西，可以说一句 —— 不想说就别说。')
  }

  return 行.join('\n')
}
